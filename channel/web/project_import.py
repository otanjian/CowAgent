# encoding:utf-8
"""The web-layer seam for the controlled project import (tasks 6.3/6.4).

Why this module exists
----------------------
``GET /api/projects/browse`` is a *read*: the worst a caller can do is learn the
names of directories inside their own root. Importing is a *write* that can copy
an arbitrary server directory into the member's project area, so it needs a
boundary the read path does not have, and it must keep the one the upstream
product already defined for it: a desktop-native selection arrives as an absolute
host path, is only valid on a **loopback** request, and must carry the
**per-start token** the local backend publishes.

This module is that boundary, and it is deliberately separate from
``channel/web/web_channel.py``:

* ``agent/workspace/project_browser.py`` owns *what* a project root is and how a
  directory is copied atomically. It knows nothing about HTTP, sessions or
  handles.
* this module owns *who may ask for what*: loopback, the per-start token, the
  verified database identity (tenant + user), the single-use handle that ties an
  import back to the preview the user actually confirmed, and the quota
  reservation the module is told to make before anything is staged.
* ``web_channel.py`` keeps thin handlers whose signatures stay where the console
  and the upstream merge expect them.

The four conditions a server-path import must satisfy
----------------------------------------------------
1. **Loopback.** ``REMOTE_ADDR`` is a loopback address *and* no forwarding
   header is present, so a reverse proxy cannot make a remote peer look local.
2. **Per-start token.** A value generated by this process and published (mode
   ``0600``) to ``local_import_token_file`` -- or pinned by ``local_import_token``
   for a supervised deployment. Only a client that can read the local filesystem
   can present it, and it does not survive a restart. Comparison is
   constant-time.
3. **Database identity.** The request runs inside the verified request context,
   so the target tenant and owner come from the session, never from the body. An
   import that names another member's session is refused before any path is read.
4. **A single-use handle.** The preview is what the user confirmed; the import
   must present the handle that preview issued, bound to the same member,
   purpose and source, and consumed on first use. A browser that simply posts a
   server path has no handle, and a replayed or re-purposed one is refused.
   Conversely the *upload* transport (a browser that cannot see a server path)
   needs no handle: it names no server path, and the session is the grant.

What it deliberately does not do
--------------------------------
It never reads a path from the request outside the local transport, never widens
allowed source roots from request data, and never re-derives ownership from the
body. The allowed extra source roots come from configuration
(``project_import_source_roots``), because a request may choose *within* a policy
but must not define one.
"""

