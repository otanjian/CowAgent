def record_import_event(identity: Any, action: str, target: str, result: str,
                        changes: Optional[Mapping[str, Any]] = None) -> None:
    """Best-effort business audit for an import attempt.

    The audit is a trace, never an authorization: a failure to record it must not
    change whether the import happened, so it is logged and swallowed. The
    payload goes through the identity service's sanitizer, and it carries counts
    and the chosen name only -- never a source path.
    """
    try:
        from auth.service import get_identity_service
        tenant_id, user_id = _binding(identity)
        get_identity_service().record_business_audit(
            actor_user_id=user_id, tenant_id=tenant_id, action=action,
            target=target, redacted_changes=dict(changes or {}), result=result)
    except Exception as e:  # noqa: BLE001 - a trace must not break the import
        logger.debug("[ProjectImport] audit %s not recorded: %s", action, e)
